import { expect, test } from '@playwright/test'

test('credential expiry stales an approved transfer until coverage is restored', async ({ page }) => {
  await page.goto('/wards/WARD-ICU/coverage/2026-09-14')
  await page.getByRole('button', { name: 'Assign to shift' }).click()
  await page.getByLabel('Candidate').selectOption('RN-6')
  await page.getByRole('button', { name: 'Assign to shift' }).click()
  await page.goto('/wards/ICU/transfers/HDU?patients=1')
  await page.getByLabel('Decision authority').selectOption('clinical lead')
  await page.getByRole('button', { name: 'Approve transfer coverage' }).click()
  await page.goto('/wards/WARD-ICU/coverage/2026-09-14')
  await page.getByText('Assigned staff and breaks').click()
  await page.getByRole('button', { name: 'Review RN-4 credential' }).click()
  await page.goto('/wards/ICU/transfers/HDU?patients=1')
  await expect(page.getByText('Transfer approval is stale', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Revalidate transfer coverage' })).toBeDisabled()
  await page.goto('/wards/WARD-ICU/coverage/2026-09-14')
  await page.getByText('Assigned staff and breaks').click()
  await page.getByRole('button', { name: 'Review RN-4 credential' }).click()
  await page.goto('/wards/ICU/transfers/HDU?patients=1')
  await page.getByLabel('Decision authority').selectOption('clinical lead')
  await page.getByRole('button', { name: 'Revalidate transfer coverage' }).click()
  await expect(page.getByText('Transfer approval is stale', { exact: false })).toHaveCount(0)
})
